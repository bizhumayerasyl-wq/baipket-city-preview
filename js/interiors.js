// Ішкі аймақта бос па (жергілікті координатпен): шекара ішінде және кедергіге тимейді (0,35 м радиус)
export function freeInside(I, lx, lz, r = .35) {
  if (Math.abs(lx) > I.hw - r || lz < I.z0 + r || lz > I.z1 - r) return false;
  return !I.obs.some(([x0, z0, x1, z1]) => lx > x0 - r && lx < x1 + r && lz > z0 - r && lz < z1 + r);
}
